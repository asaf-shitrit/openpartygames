#!/usr/bin/env node
// Validate every content pack, then write apps/worker/.wrangler/pack-seed.sql:
// a full delete + reinsert of the `packs` and `pack_items` D1 tables.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadPacks, validatePack } from "./pack-rules.mjs";

const rootDir = fileURLToPath(new URL("..", import.meta.url));
const entries = loadPacks(rootDir);

const errors = [];
for (const entry of entries) {
  for (const message of validatePack(entry.pack, entry)) {
    errors.push(`packs/${entry.folder}/${entry.filename}: ${message}`);
  }
}

if (errors.length > 0) {
  console.error(
    `✗ ${errors.length} pack error${errors.length === 1 ? "" : "s"}; refusing to write the seed:`,
  );
  for (const message of errors) console.error(`  ${message}`);
  process.exit(1);
}

const sorted = entries.toSorted(byPackId);

/** Stable pack order for the seed, so regenerating it produces a diff-only-when-changed file. */
function byPackId(a, b) {
  if (a.pack.id < b.pack.id) return -1;
  if (a.pack.id > b.pack.id) return 1;
  return 0;
}

const quote = (value) =>
  value === undefined || value === null
    ? "NULL"
    : `'${String(value).replace(/'/g, "''")}'`;

const lines = [
  "-- Generated by scripts/build-pack-seed.mjs. Do not edit by hand.",
  "DELETE FROM pack_items;",
  "DELETE FROM packs;",
];

let itemCount = 0;
for (const { pack } of sorted) {
  lines.push("");
  lines.push(
    "INSERT INTO packs (id, name, kind, rating, language, license, attribution, item_count) VALUES (" +
      [
        quote(pack.id),
        quote(pack.name),
        quote(pack.kind),
        quote(pack.rating),
        quote(pack.language),
        quote(pack.license),
        quote(pack.attribution),
        String(pack.items.length),
      ].join(", ") +
      ");",
  );
  pack.items.forEach((item, index) => {
    lines.push(
      "INSERT INTO pack_items (pack_id, idx, data) VALUES (" +
        `${quote(pack.id)}, ${index}, ${quote(JSON.stringify(item))}` +
        ");",
    );
    itemCount += 1;
  });
}

const outputDir = path.join(rootDir, "apps", "worker", ".wrangler");
fs.mkdirSync(outputDir, { recursive: true });
fs.writeFileSync(
  path.join(outputDir, "pack-seed.sql"),
  lines.join("\n") + "\n",
  "utf8",
);

console.log(
  `Wrote apps/worker/.wrangler/pack-seed.sql (${sorted.length} packs, ${itemCount} items)`,
);
