// The meter behind `one-minute.spec.ts`: what one walk through the app costs in screens,
// taps and typed fields, and the markdown record that walk writes.
//
// The record is the point. A step added to the path — a confirm, an extra picker — lands as a
// different number in a checked-in file, so review sees it as a diff instead of not seeing it
// at all. Nothing here fails on a count: a longer path is a decision for a person, not a red
// suite.
import { devices, type Browser, type Page } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const METER_PATH = fileURLToPath(
  new URL("./one-minute-meter.js", import.meta.url),
);

/**
 * Goal 1 gives a room a minute from the first tap to the first game phase. The cost model
 * turns a walk into seconds: three seconds to find and tap a control, six to read a field and
 * type into it. Reading a room code aloud, waiting on a phone network, and a screen that
 * holds no control are deliberately not counted — they are not steps anyone can remove.
 */
export const BUDGET_SECONDS = 60;
export const SECONDS_PER_TAP = 3;
export const SECONDS_PER_FIELD = 6;

export interface Counts {
  screens: number;
  taps: number;
  fields: number;
}

export interface PathRow {
  label: string;
  counts: Counts;
}

declare global {
  interface Window {
    opgMeter?: { snapshot: () => Counts };
  }
}

const NOTHING: Counts = { screens: 0, taps: 0, fields: 0 };

async function readCounts(page: Page): Promise<Counts> {
  return page.evaluate(() => {
    const meter = window.opgMeter;
    if (meter === undefined) return { screens: 0, taps: 0, fields: 0 };
    return meter.snapshot();
  });
}

function difference(now: Counts, before: Counts): Counts {
  return {
    screens: now.screens - before.screens,
    taps: now.taps - before.taps,
    fields: now.fields - before.fields,
  };
}

function sum(tally: Counts, counts: Counts): Counts {
  return {
    screens: tally.screens + counts.screens,
    taps: tally.taps + counts.taps,
    fields: tally.fields + counts.fields,
  };
}

/** One walk through the app: who made it, and a row per interval between two marks. */
export class OneMinutePath {
  private seen: Counts = NOTHING;
  readonly rows: PathRow[] = [];

  constructor(
    readonly page: Page,
    readonly who: string,
  ) {}

  /** Closes the interval that opened at the previous mark, named by what happened in it. */
  async mark(label: string): Promise<void> {
    const now = await readCounts(this.page);
    this.rows.push({ label, counts: difference(now, this.seen) });
    this.seen = now;
  }

  get total(): Counts {
    return this.rows.reduce((tally, row) => sum(tally, row.counts), NOTHING);
  }
}

/** A phone-shaped context that counts its walk, built the way `newPhonePage` builds one. */
export async function meteredPhone(
  browser: Browser,
  who: string,
): Promise<OneMinutePath> {
  const context = await browser.newContext({
    ...devices["Pixel 5"],
    reducedMotion: "reduce",
  });
  await context.addInitScript({ path: METER_PATH });
  const page = await context.newPage();
  return new OneMinutePath(page, who);
}

/** The walk in seconds under the cost model above. */
export function seconds(counts: Counts): number {
  return counts.taps * SECONDS_PER_TAP + counts.fields * SECONDS_PER_FIELD;
}

function tableRow(label: string, counts: Counts): string {
  return `| ${label} | ${counts.screens} | ${counts.taps} | ${counts.fields} | ${seconds(counts)}s |`;
}

const HEAD = "| interval | screens | taps | typed fields | cost |\n| --- | --- | --- | --- | --- |";

function summary(paths: readonly OneMinutePath[]): string {
  const head = "| who | screens | taps | typed fields | cost |\n| --- | --- | --- | --- | --- |";
  const rows = paths.map((path) => tableRow(path.who, path.total));
  return [head, ...rows].join("\n");
}

function walk(path: OneMinutePath): string {
  const rows = path.rows.map((row) => tableRow(row.label, row.counts));
  return [`## ${path.who}`, "", HEAD, ...rows].join("\n");
}

function fits(worst: number): string {
  if (worst <= BUDGET_SECONDS) return `Fits the ${BUDGET_SECONDS}s budget.`;
  return `Over the ${BUDGET_SECONDS}s budget by ${worst - BUDGET_SECONDS}s.`;
}

const PREAMBLE = [
  "Written by `e2e/browser/one-minute.spec.ts`. Do not edit this file by hand.",
  "Run `pnpm e2e:browser -g one-minute` and commit the file it writes.",
  "",
  "The tables count screens, taps and typed fields between the landing page and",
  "the first game phase. A step added to that path changes a number here, so",
  "review sees it as a diff.",
  "",
  `Budget: ${BUDGET_SECONDS} seconds, from the first tap to the first game phase (goal 1).`,
  `Cost model: ${SECONDS_PER_TAP} seconds for a tap, ${SECONDS_PER_FIELD} seconds for a typed field.`,
  "A room code read aloud, a wait on the network, and a screen with no control on",
  "it cost nothing.",
  "",
];

export interface WalkRecord {
  title: string;
  note: string;
  paths: readonly OneMinutePath[];
}

export function formatRecord(walked: WalkRecord): string {
  const costs = walked.paths.map((path) => seconds(path.total));
  return [
    `# ${walked.title}`,
    "",
    ...PREAMBLE,
    summary(walked.paths),
    "",
    walked.note,
    "",
    fits(Math.max(...costs)),
    "",
    walked.paths.map(walk).join("\n\n"),
    "",
  ].join("\n");
}

const RECORD_DIR = fileURLToPath(new URL("./one-minute/", import.meta.url));

/** Writes one record under e2e/browser/one-minute and returns its path. */
export function writeRecord(name: string, markdown: string): string {
  mkdirSync(RECORD_DIR, { recursive: true });
  const file = `${RECORD_DIR}${name}.md`;
  writeFileSync(file, markdown, "utf8");
  return file;
}

/** Puts the record in the suite's own output, where QA reads the numbers without a checkout. */
export function printRecord(markdown: string): void {
  process.stdout.write(`\n${markdown}\n`);
}
